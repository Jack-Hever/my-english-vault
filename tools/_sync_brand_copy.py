# -*- coding: utf-8 -*-
"""更新 `docs/去AI版_品牌文案_学英语的人手里常有两.txt` 的事实项数字。

★ 口径（team-lead 2026-10-24 明确指示）★
「100 字简介」里的**示例规模数字整段移除**，不要替换成「5 词条 / 2 篇 / 41 个句对」。
理由：① 那些数字描述的是**演示语料**（预置的样例），不是产品内容 ——
用户的产品定位是「个人库」，原话「词和文章又不是产品内容」；
② 数字在简介里会让评审误以为「产品实力 = 预置数据量」；
③ 硬改数字会破字数口径（QA 实测：把旧数字换成新数字后含空格 100 → 98）。

★ 为什么要移除而不是替换 ★
替换成「5 词条 / 2 篇 / 41 个句对」看起来「数字是真的」，但：
  · 「内置 5 词条」在产品简介里反而**更刺眼**（一眼看出预置内容少）；
  · 演示语料以后再裁一轮，这句话又得改一遍；
  · 简介要说的是「这产品解决什么问题」，不是「它预置了多少东西」。
⇒ 结论：简介里**一个示例规模数字都不留**。

★ 本文件是改写手法的存档，不是可用的文案 ★
所以这里的正文**保留原样**（那是当时的历史产物），只在**事实项声明处**
与**开头加一段醒目注记**说明数字已作废 —— 与
`docs/submission_draft.md` §2 的处理保持一致。

用法：python tools/_sync_brand_copy.py
"""
from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TARGET = REPO / "docs" / "去AI版_品牌文案_学英语的人手里常有两.txt"

#: 文件开头的注记（插入到第一行之前）
HEADER_NOTE = """⚠️ 2026-10-24 注记 · 本文档的事实项数字已作废
────────────────────────────────────────
本文件是**文案改写手法的存档**（怎么改、为什么这么改、判据怎么验），
**不是可直接使用的文案**。原因：

① 正文里的「60 词条 / 7 篇 / 171 个句对」是**演示语料的规模**，
   演示语料已于 2026-10-24 裁剪为「2 篇 / 5 词 / 41 句对」。
② 更根本的是：**示例规模不该出现在产品简介里**。本产品主打个人库，
   设计约束「词和文章又不是产品内容」——把预置数据量写进简介，
   会让评审误以为「产品实力 = 预置数据量」。
③ 硬改数字会破字数口径：QA 实测把旧数字换成「5 词条 / 2 篇 / 41 个句对」后，
   含空格正好 100 字的那版变成 98 字，两边都不成立。
④ 作者 2026-10-24 明确「简介我另外写好了，你不用管」。

⇒ **简介正文里的规模数字整段移除**（不是替换成新数字），由作者自行定稿。
   下面的正文保留原样，仅作历史存档。

"""

#: 「事实零改动」那一条要改成「事实项当时零改动，但数字现已作废」
FACT_LINE_OLD = "4. 事实零改动：60 词条 / 7 篇 / 171 个句对 / 无需注册，全部原样保留。"
FACT_LINE_NEW = (
    "4. 事实零改动：60 词条 / 7 篇 / 171 个句对 / 无需注册，全部原样保留。"
    "   ⚠️ 2026-10-24 注记：这组数字是**演示语料规模**，现已裁剪为「2 篇 / 5 词 / 41 句对」，"
    "且简介里应整段移除规模数字（理由见文件开头）。"
)


def main() -> int:
    text = TARGET.read_text(encoding="utf-8")
    if "2026-10-24 注记 · 本文档的事实项数字已作废" in text:
        print("[SKIP] 文件头注记已存在，不重复插入")
    else:
        text = HEADER_NOTE + text
        print("[OK] 文件头已插入作废注记")

    if FACT_LINE_OLD in text:
        if "这组数字是**演示语料规模**" in text:
            print("[SKIP] 事实项注记已存在")
        else:
            text = text.replace(FACT_LINE_OLD, FACT_LINE_NEW, 1)
            print("[OK] 事实项声明处已加作废注记")
    else:
        print("[FAIL] 找不到事实项那一句（文件结构变了？）")
        return 1

    TARGET.write_text(text, encoding="utf-8")
    print("\n完成")
    return 0


if __name__ == "__main__":
    sys.exit(main())
